namespace Flowbite.Blazor.Enums
{
    /// <summary>
    /// Specifies anchor positions for UI elements.
    /// </summary>
    public enum Anchors
    {
        /// <summary>
        /// No specific anchor is set.
        /// </summary>
        None = 0,

        /// <summary>
        /// Anchors to the top center.
        /// </summary>
        Top = 1,

        /// <summary>
        /// Anchors to the right center.
        /// </summary>
        Right = 2,

        /// <summary>
        /// Anchors to the bottom center.
        /// </summary>
        Bottom = 3,

        /// <summary>
        /// Anchors to the left center.
        /// </summary>
        Left = 4,

        /// <summary>
        /// Anchors to the top-right corner.
        /// </summary>
        TopRight = 5,

        /// <summary>
        /// Anchors to the bottom-right corner.
        /// </summary>
        BottomRight = 6,

        /// <summary>
        /// Anchors to the top-left corner.
        /// </summary>
        TopLeft = 7,

        /// <summary>
        /// Anchors to the bottom-left corner.
        /// </summary>
        BottomLeft = 8,
    }
}
